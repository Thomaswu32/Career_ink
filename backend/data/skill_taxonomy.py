for _cat, _skills in SKILL_TAXONOMY.items():
    for _skill in _skills:
        if _cat == SOFT_SKILLS_CATEGORY:
            if _skill not in SOFT_SKILLS:
                SOFT_SKILLS.append(_skill)
        else:
            if _skill not in HARD_SKILLS:
                HARD_SKILLS.append(_skill)
